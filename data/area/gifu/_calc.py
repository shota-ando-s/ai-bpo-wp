def man(yen):
    """円 → 万円（小数1桁、四捨五入）。yen は Decimal"""
    return (yen / Decimal(10000)).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)


def existing():
    rows = []
    for pref in ("fukui", "ishikawa"):
        for f in sorted(glob.glob(f"{ART}/2026-10-27-area-{pref}-*.md")):
            t = open(f, encoding="utf-8").read()
            h = re.search(r"^\| 月の削減時間 \| ([\d.]+)時間", t, re.M)
            m = re.search(r"^\| 月の時間換算額（年間） \| 約([\d.]+)万円", t, re.M)
            s = re.search(r"^## 試算：.*?従業員(\d+)名", t, re.M)
            name = f.rsplit("/", 1)[1]
            if not (h and m and s):
                print("読み取れない:", name)
                continue
            rows.append((name, Decimal(h.group(1)), Decimal(m.group(1)), int(s.group(1))))
    return rows


def main():
    ex = existing()
    print(f"既存のページ: {len(ex)}（福井17＋石川19＝36 のはず）")
    ex_h = {r[1]: r[0] for r in ex}
    ex_m = {r[2]: r[0] for r in ex}
    ex_s = {r[3]: r[0] for r in ex}

    ok = True
    seen_h, seen_m, seen_s = {}, {}, {}
    print("| 市町村 | 業種（業態） | 従業員 | 対象人数×業務量×25% | 月の削減時間 | 時間単価 | 月の時間換算額 | 年間 |")
    for (city, slug, ind, sub, size, task, n, hrs) in PLAN:
        h = Decimal(str(n)) * Decimal(str(hrs)) * Decimal("0.25")
        yen = h * RATE[ind]
        m = man(yen)
        y = man(yen * 12)
        print(f"| {city} | {ind}（{sub}） | {size}名 | {n}名×{hrs}h×25% | {h.normalize():f}h | {RATE[ind]:,}円 | 約{m}万円 | 約{y}万円 |")
        for label, key, seen, exd in (("時間", h, seen_h, ex_h), ("金額", m, seen_m, ex_m), ("規模", size, seen_s, ex_s)):
            if key in seen:
                print(f"  NG 岐阜の中で{label}が重なる: {city} と {seen[key]} ({key})")
                ok = False
            seen[key] = city
            if key in exd:
                print(f"  NG 福井・石川と{label}が重なる: {city} と {exd[key]} ({key})")
                ok = False
        if (h * 2) % 1 != 0:
            print(f"  NG {city} の時間が0.5時間刻みでない ({h})")
            ok = False
        if (yen / Decimal(500)) % 2 == 1:
            print(f"  注意: {city} の金額が四捨五入の境目（{yen}円）")
    print(f"\n42ページ: {len(PLAN)}、slug の重なり: {len(PLAN) - len({p[1] for p in PLAN})}")
    print(f"時間の範囲 {min(seen_h)}〜{max(seen_h)}h、金額の範囲 {min(seen_m)}〜{max(seen_m)}万円、規模 {min(seen_s)}〜{max(seen_s)}名")
    from collections import Counter
    print("業種の内訳:", dict(Counter(p[2] for p in PLAN)))
    print("OK" if ok and len(PLAN) == 42 else "NG")


if __name__ == "__main__":
    main()
